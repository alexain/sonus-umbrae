const SCALE_INDEX = new Map<string, ScaleDefinition>();
for (const scale of SCALE_CATALOG) {
  SCALE_INDEX.set(scale.id.toLowerCase(), scale);
  for (const alias of scale.aliases ?? []) SCALE_INDEX.set(alias.toLowerCase(), scale);
}

export function findScaleDefinition(name: string): ScaleDefinition | undefined {
  return SCALE_INDEX.get(name.trim().toLowerCase());
}

export function scalesForEdo(edo: SupportedEdo): readonly ScaleDefinition[] {
  return SCALE_CATALOG.filter((scale) => scale.edo === edo);
}

export function edoStepCents(edo: SupportedEdo): number {
  return 1200 / edo;
}
